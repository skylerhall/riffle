"""
Riffle -> Guppy -> HUGR: run Riffle circuits on Quantinuum's software stack.

Quantinuum's language, Guppy, compiles to HUGR, a graph-based format for
quantum-classical programs, and its open-source Selene emulator runs HUGR.
This module writes a Riffle circuit as a Guppy program, lets Guppy's own
compiler produce the HUGR (so the output is valid by construction), and can
run it on Selene to check the results against Riffle's simulator.

    pip install guppylang selene-sim

    from quantinuum import to_guppy, to_hugr, run_selene
    print(to_guppy(c))                 # the Guppy source
    pkg = to_hugr(c, "bell.hugr")      # HUGR package, also saved to a file
    counts = run_selene(c, shots=2000) # {"00": 1013, "11": 987}

Command line:
    python quantinuum.py               # export every preset to hugr/ and check each on Selene

Like Riffle, Guppy treats qubits as values that can't be copied (linear
types), so the two fit naturally: every Riffle wire becomes one Guppy
variable, and a SWAP is just a renaming, with no gates at all.
"""
from __future__ import annotations

import importlib.util
import math
import pathlib
import sys
import tempfile
import warnings

HERE = pathlib.Path(__file__).resolve().parent

_ONE = {"H": "h", "X": "x", "Y": "y", "Z": "z", "S": "s", "T": "t"}
_ROT = {"RX": "rx", "RY": "ry", "RZ": "rz"}
_TWO = {"CX": "cx", "CZ": "cz", "CCX": "toffoli"}


def to_guppy(c, name="main"):
    """Guppy source for a Riffle circuit. Measures the main qubits into results
    q0, q1, ...; work qubits are discarded (they're back at |0> when cleanup is on)."""
    steps = c.compile()
    work = getattr(c, "work", 0)
    lines = [f"q{i}" for i in range(c.n)] + [f"w{k}" for k in range(work)]
    var = list(lines)                                 # which Guppy variable holds each qubit line now
    used = sorted({_ONE.get(g.name) or _ROT.get(g.name) or _TWO.get(g.name) for _, g, _ in steps} - {None})
    imports = ", ".join(["qubit", "measure", "discard"] + used + (["angle"] if any(g.name in _ROT for _, g, _ in steps) else []))
    out = [
        f'"""Generated by Riffle from a {c.n}-qubit circuit'
        + (f" with {work} work qubit{'s' if work > 1 else ''}" if work else "") + '."""',
        "from guppylang import guppy",
        f"from guppylang.std.quantum import {imports}",
        "from guppylang.std.builtins import result",
        "",
        "",
        "@guppy",
        f"def {name}() -> None:",
        "    " + "; ".join(f"{v} = qubit()" for v in lines),
    ]
    for node, gate, qs in steps:
        args = [var[q] for q in qs]
        tag = "  # cleanup, added by Riffle" if getattr(gate, "auto", False) else f"  # {node}"
        if gate.name in _ONE:
            out.append(f"    {_ONE[gate.name]}({args[0]}){tag}")
        elif gate.name in _ROT:
            half_turns = gate.params[0] / math.pi           # Guppy angles count half-turns, Riffle's θ/π
            out.append(f"    {_ROT[gate.name]}({args[0]}, angle({half_turns!r})){tag}")
        elif gate.name in _TWO:
            out.append(f"    {_TWO[gate.name]}({', '.join(args)}){tag}")
        elif gate.name == "SWAP":                         # linear qubits: a swap is a renaming
            a, b = qs
            var[a], var[b] = var[b], var[a]
            out.append(f"    # {node}: SWAP is a relabel in Guppy, no gate needed")
        else:
            raise ValueError(f"{gate.name} has no Guppy equivalent")
    for i in range(c.n):
        out.append(f'    result("c{i}", measure({var[i]}).read())')
    for k in range(work):
        out.append(f"    discard({var[c.n + k]})")
    return "\n".join(out) + "\n"


def _load(c, name="main"):
    """Write the Guppy source to a file (Guppy reads source files) and import it."""
    warnings.filterwarnings("ignore")
    src = to_guppy(c, name)
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="riffle_guppy_")) / "riffle_circuit.py"
    tmp.write_text(src)
    spec = importlib.util.spec_from_file_location(f"riffle_circuit_{id(c)}", tmp)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return getattr(mod, name)


def to_hugr(c, path=None):
    """Compile to a HUGR package with Guppy's compiler; optionally save it (.hugr envelope)."""
    pkg = _load(c).compile()
    if path:
        pathlib.Path(path).write_bytes(pkg.to_bytes())
    return pkg


_QOPS = {"QAlloc", "QFree", "H", "X", "Y", "Z", "S", "T", "Rx", "Ry", "Rz", "CX", "CZ", "Toffoli", "MeasureFree"}


def hugr_summary(pkg):
    """A quick look inside the HUGR graph: node count and the quantum operations it holds."""
    from collections import Counter

    ops, nodes = Counter(), 0
    for mod in pkg.modules:
        for _, data in mod.nodes():
            nodes += 1
            op_def = getattr(data.op, "op_def", None)
            name = op_def().name if callable(op_def) else ""
            if name in _QOPS:
                ops[name] += 1
    return {"nodes": nodes, "quantum_ops": dict(sorted(ops.items()))}


def run_selene(c, shots=2000, seed=7):
    """Run on Quantinuum's Selene emulator. Returns counts keyed like Riffle (q0 first)."""
    fn = _load(c)
    total = c.n + getattr(c, "work", 0)
    res = fn.emulator(n_qubits=total).with_shots(shots).with_seed(seed).run()
    counts = {}
    for key, n in res.collated_counts().items():
        bits = dict(key)
        b = "".join(str(bits[f"c{i}"]) for i in range(c.n))
        counts[b] = counts.get(b, 0) + n
    return dict(sorted(counts.items()))


def fidelity(ideal, counts, shots):
    keys = set(ideal) | set(counts)
    return sum(math.sqrt(ideal.get(k, 0) * counts.get(k, 0) / shots) for k in keys) ** 2


def main(keys=None, shots=2000):
    sys.path.insert(0, str(HERE))
    from run_ibm import PRESETS, build

    out = HERE / "hugr"
    out.mkdir(exist_ok=True)
    print(f"{'circuit':<38} {'HUGR nodes':>10}  {'Selene vs Riffle':>18}")
    worst = 1.0
    for k in keys or PRESETS:
        label, c = build(k)
        pkg = to_hugr(c, out / f"{k}.hugr")
        (out / f"{k}_guppy.py").write_text(to_guppy(c))
        counts = run_selene(c, shots=shots)
        f = fidelity(c.run().probabilities, counts, shots)
        worst = min(worst, f)
        summ = hugr_summary(pkg)
        print(f"{label:<38} {summ['nodes']:>10}  {f:>17.1%}   {counts}")
    print(f"\nSaved .hugr packages and Guppy source to {out}/")
    return worst


if __name__ == "__main__":
    main()
